#!/usr/bin/env node
/**
 * Release gate for a store submission. Lists every open gate and exits 1 while
 * any remain; exits 0 when all pass. Node ESM, no dependencies.
 *
 *   node scripts/store/check-release-config.mjs          # human report
 *   node scripts/store/check-release-config.mjs --json   # { open, warnings, passed }
 *
 * Gates (each is an exported function returning a list of problems, [] = pass,
 * so __tests__/storeReleaseConfig.test.ts can call them on fixtures):
 *   privacy-url          checkPrivacyUrl            EXPO_PUBLIC_PRIVACY_POLICY_URL, https
 *   sentry-upload        checkSentryUpload          production must upload source maps
 *   submit-placeholders  checkSubmitPlaceholders    REPLACE_WITH_ left in eas.json submit
 *   contact-placeholders checkContactPlaceholders   constants/foundationContact.ts
 *   native-config        checkNativeConfig          identifiers, blocked permissions, plugins
 *   local-privacy-manifest (warning) checkLocalPrivacyManifest  generated PrivacyInfo.xcprivacy
 *
 * CONTRACT with constants/foundationContact.ts (a TypeScript module, so it is
 * read as text, not imported): it exports FOUNDATION_CONTACT, and every value
 * the Foundation has not yet confirmed is a quoted string starting with
 * `PLACEHOLDER_`. The gate counts quoted values
 * matching /'PLACEHOLDER_[A-Z0-9_]+'/g and is open while the file is missing or
 * that count is above zero. Comments may mention the word freely.
 *
 * sentry-upload has two conditions: SENTRY_DISABLE_AUTO_UPLOAD must be gone from
 * production, and the SENTRY_AUTH_TOKEN variable must exist in EAS. The second is
 * looked up with `eas env:list` (falling back to `secret:list`), 20s timeout,
 * output never printed. When the CLI is missing, logged out or errors, the gate
 * stays open unless you pass --confirm-sentry-secret or set
 * KHZ_CONFIRM_SENTRY_SECRET=1. KHZ_SKIP_EAS_CLI=1 skips the CLI (test seam).
 *
 * The generated PrivacyInfo.xcprivacy check is a warning: the ios/ directory is
 * regenerated by prebuild, but a prebuild MERGE only adds keys, so a stale local
 * ios/ can carry a data type app.json no longer declares.
 */
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

export const EXPECTED_ID = 'com.khazayin.app';
export const REQUIRED_BLOCKED = [
  'SYSTEM_ALERT_WINDOW',
  'READ_EXTERNAL_STORAGE',
  'WRITE_EXTERNAL_STORAGE',
  'ACCESS_FINE_LOCATION',
  'USE_EXACT_ALARM',
  'SCHEDULE_EXACT_ALARM',
  'ACCESS_BACKGROUND_LOCATION',
  'FOREGROUND_SERVICE_LOCATION',
].map((p) => `android.permission.${p}`);
export const CONTACT_FILE = 'constants/foundationContact.ts';

const prod = (eas) => eas?.build?.production?.env ?? {};

export function checkPrivacyUrl(eas, env = {}) {
  const url = prod(eas).EXPO_PUBLIC_PRIVACY_POLICY_URL ?? env.EXPO_PUBLIC_PRIVACY_POLICY_URL;
  if (!url) {
    return ['EXPO_PUBLIC_PRIVACY_POLICY_URL is not set in eas.json build.production.env or the environment'];
  }
  if (!String(url).startsWith('https://')) {
    return [`EXPO_PUBLIC_PRIVACY_POLICY_URL must start with https:// (got "${url}")`];
  }
  return [];
}

/** True when eas-cli output (JSON or text) lists a variable named SENTRY_AUTH_TOKEN. Never returns or logs values. */
export function sentrySecretInOutput(output) {
  return /(^|[^A-Z0-9_])SENTRY_AUTH_TOKEN([^A-Z0-9_]|$)/.test(String(output));
}

// eas-cli >= 16: `env:list [ENVIRONMENT]` (short format hides sensitive values;
// there is no JSON format, so the output is matched as text). `secret:list` is
// the pre-env CLI's command, used ONLY when env:list does not exist: on a
// current CLI it is deprecated and reports an empty list with exit 0, which
// would be a false "absent".
const ENV_LIST = ['env:list', 'production'];
const SECRET_LIST = ['secret:list', '--json'];

/**
 * Ask eas-cli whether the SENTRY_AUTH_TOKEN variable exists. Returns
 * { status: 'found' | 'absent' | 'unavailable', detail? }. Bounded by a short
 * timeout so it can never hang the script; no output is ever echoed.
 *
 * Test seam: KHZ_SKIP_EAS_CLI=1 skips the CLI entirely (jest sets it, so the
 * suite needs no network, login or eas-cli install).
 */
export function lookupSentrySecret(env = process.env) {
  if (env.KHZ_SKIP_EAS_CLI === '1') {
    return { status: 'unavailable', detail: 'eas-cli lookup skipped (KHZ_SKIP_EAS_CLI=1)' };
  }
  const runners = [['eas', []], ['npx', ['--no-install', 'eas-cli']]];
  const run = (cmd, pre, args) =>
    spawnSync(cmd, [...pre, ...args], {
      cwd: ROOT,
      encoding: 'utf8',
      timeout: 20000,
      stdio: ['ignore', 'pipe', 'pipe'],
      env: { ...env, CI: '1' },
    });
  let lastDetail = 'eas-cli not found';
  for (const [cmd, pre] of runners) {
    let r = run(cmd, pre, ENV_LIST);
    if (r.error) {
      lastDetail = r.error.code === 'ENOENT' ? `${cmd} not found` : `${cmd} failed (${r.error.code ?? r.error.message})`;
      continue;
    }
    if (r.status !== 0 && /command\s+env:list\s+not found|is not an? eas command/i.test(`${r.stderr}`)) {
      r = run(cmd, pre, SECRET_LIST); // CLI predates env:list
      if (r.error) {
        lastDetail = `${cmd} failed (${r.error.code ?? r.error.message})`;
        continue;
      }
    }
    if (r.status === 0) {
      return { status: sentrySecretInOutput(r.stdout) ? 'found' : 'absent' };
    }
    // The runner executed and failed (logged out, network, ...): another runner
    // would hit the same wall, so stop instead of spawning the rest.
    return { status: 'unavailable', detail: 'eas-cli errored or is not logged in' };
  }
  return { status: 'unavailable', detail: lastDetail };
}

/**
 * Two independent conditions: (1) production must not disable the upload;
 * (2) the SENTRY_AUTH_TOKEN EAS variable must exist. For (2), when the CLI
 * cannot answer, the gate is open unless the operator confirms the secret
 * (--confirm-sentry-secret or KHZ_CONFIRM_SENTRY_SECRET=1).
 * @param {{confirmed?: boolean, lookup?: () => {status: string, detail?: string}}} ctx
 */
export function checkSentryUpload(eas, ctx = {}) {
  const problems = [];
  if (prod(eas).SENTRY_DISABLE_AUTO_UPLOAD === 'true') {
    problems.push(
      'production sets SENTRY_DISABLE_AUTO_UPLOAD=true: after the SENTRY_AUTH_TOKEN EAS secret exists, remove SENTRY_DISABLE_AUTO_UPLOAD from build.production.env',
    );
  }
  const result = (ctx.lookup ?? lookupSentrySecret)();
  if (result.status === 'absent') {
    problems.push('the SENTRY_AUTH_TOKEN EAS variable does not exist in the production environment: create it (eas env:set, visibility secret)');
  } else if (result.status === 'unavailable' && !ctx.confirmed) {
    problems.push(
      `SENTRY_AUTH_TOKEN EAS secret could not be verified (${result.detail ?? 'eas-cli unavailable'}): create it, then re-run with --confirm-sentry-secret or KHZ_CONFIRM_SENTRY_SECRET=1`,
    );
  }
  return problems;
}

export function checkSubmitPlaceholders(eas) {
  const found = [];
  const walk = (node, trail) => {
    if (typeof node === 'string') {
      if (node.includes('REPLACE_WITH_')) found.push(`eas.json ${trail.join('.')} is still "${node}"`);
    } else if (node && typeof node === 'object') {
      for (const [k, v] of Object.entries(node)) walk(v, [...trail, k]);
    }
  };
  walk(eas?.submit, ['submit']);
  return found;
}

/** Quoted unverified values in the contact module's text (the gate's contract). */
export function placeholderCount(text) {
  return (text.match(/'PLACEHOLDER_[A-Z0-9_]+'/g) ?? []).length;
}

/** @param {string|null} text contents of constants/foundationContact.ts, null if missing */
export function checkContactPlaceholders(text) {
  if (text == null) return [`${CONTACT_FILE} missing`];
  const n = placeholderCount(text);
  return n > 0 ? [`${CONTACT_FILE} still has ${n} PLACEHOLDER value(s)`] : [];
}

export function checkNativeConfig(expo) {
  const problems = [];
  if (expo?.ios?.bundleIdentifier !== EXPECTED_ID) {
    problems.push(`ios.bundleIdentifier is "${expo?.ios?.bundleIdentifier}", expected ${EXPECTED_ID}`);
  }
  if (expo?.android?.package !== EXPECTED_ID) {
    problems.push(`android.package is "${expo?.android?.package}", expected ${EXPECTED_ID}`);
  }
  const blocked = expo?.android?.blockedPermissions ?? [];
  const missing = REQUIRED_BLOCKED.filter((p) => !blocked.includes(p));
  if (missing.length) problems.push(`android.blockedPermissions is missing: ${missing.join(', ')}`);
  const names = (expo?.plugins ?? []).map((p) => (Array.isArray(p) ? p[0] : p));
  if (names.some((n) => String(n).includes('withExactAlarmPermissions'))) {
    problems.push('plugins still registers withExactAlarmPermissions (exact alarms are out of v1)');
  }
  return problems;
}

/** @param {string} plistText generated PrivacyInfo.xcprivacy */
export function checkLocalPrivacyManifest(plistText, expo) {
  const declared = new Set(
    (expo?.ios?.privacyManifests?.NSPrivacyCollectedDataTypes ?? []).map((t) => t.NSPrivacyCollectedDataType),
  );
  const present = [
    ...plistText.matchAll(/<key>NSPrivacyCollectedDataType<\/key>\s*<string>([^<]+)<\/string>/g),
  ].map((m) => m[1]);
  return present
    .filter((t) => !declared.has(t))
    .map((t) => `generated PrivacyInfo.xcprivacy declares ${t}, which app.json does not (stale ios/? run prebuild --clean)`);
}

function readJson(file) {
  return JSON.parse(readFileSync(path.join(ROOT, file), 'utf8'));
}

function findLocalPrivacyManifest() {
  const iosDir = path.join(ROOT, 'ios');
  if (!existsSync(iosDir)) return null;
  for (const d of readdirSync(iosDir)) {
    const f = path.join(iosDir, d, 'PrivacyInfo.xcprivacy');
    if (existsSync(f)) return f;
  }
  return null;
}

export function runAll(env = process.env, argv = process.argv) {
  const eas = readJson('eas.json');
  const expo = readJson('app.json').expo;
  const contactPath = path.join(ROOT, CONTACT_FILE);
  const contact = existsSync(contactPath) ? readFileSync(contactPath, 'utf8') : null;
  const plist = findLocalPrivacyManifest();

  const gates = [
    ['privacy-url', checkPrivacyUrl(eas, env)],
    [
      'sentry-upload',
      checkSentryUpload(eas, {
        confirmed: argv.includes('--confirm-sentry-secret') || env.KHZ_CONFIRM_SENTRY_SECRET === '1',
        lookup: () => lookupSentrySecret(env),
      }),
    ],
    ['submit-placeholders', checkSubmitPlaceholders(eas)],
    ['contact-placeholders', checkContactPlaceholders(contact)],
    ['native-config', checkNativeConfig(expo)],
  ];
  const open = gates.flatMap(([id, ps]) => ps.map((message) => ({ id, message })));
  const warnings = plist
    ? checkLocalPrivacyManifest(readFileSync(plist, 'utf8'), expo).map((message) => ({
        id: 'local-privacy-manifest',
        message,
      }))
    : [];
  return { open, warnings, passed: gates.filter(([, ps]) => !ps.length).map(([id]) => id) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const report = runAll();
  if (process.argv.includes('--json')) {
    console.log(JSON.stringify(report, null, 2));
  } else {
    for (const id of report.passed) console.log(`PASS  ${id}`);
    for (const g of report.open) console.log(`OPEN  ${g.id}: ${g.message}`);
    for (const w of report.warnings) console.log(`WARN  ${w.id}: ${w.message}`);
    console.log(
      report.open.length
        ? `\n${report.open.length} open gate(s): not ready to release.`
        : '\nAll release gates pass.',
    );
  }
  process.exit(report.open.length ? 1 : 0);
}
